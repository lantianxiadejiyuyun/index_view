/** 去掉「市 / 省 / 区 / 县 / 自治州」这种后缀，也去掉空白 */
function normalize(raw: string): string {
  return raw
    .trim()
    .replace(/\s+/g, '')
    .replace(/(特别行政区|自治区|自治州|地区|城市|市|省|区|县)$/u, '')
}

/**
 * 查内置坐标。命中返回经纬度，没命中返回 null（调用方再去问在线接口）。
 */
export function lookupCity(raw: string): { name: string; latitude: number; longitude: number } | null {
  if (!raw) return null

  const key = normalize(raw)
  const hit = CITIES[key]
  if (hit) return { name: key, latitude: hit[0], longitude: hit[1] }

  // 拼音 / 英文名（统一转小写、去掉多余空白与连字符）
  const ascii = raw.trim().toLowerCase().replace(/[-_]/g, ' ')
  const mapped = PINYIN[ascii] ?? PINYIN[ascii.replace(/\s+/g, '')]
  if (mapped) {
    const c = CITIES[mapped]
    if (c) return { name: mapped, latitude: c[0], longitude: c[1] }
  }

  return null
}

