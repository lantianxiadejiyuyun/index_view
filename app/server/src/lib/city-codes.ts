/** 去掉「市 / 省 / 区 / 县 / 自治州」这类后缀，也去掉空白 */
function normalize(raw: string): string {
  return raw
    .trim()
    .replace(/\s+/g, '')
    .replace(/(特别行政区|自治区|自治州|地区|新区|城市|市|省|区|县)$/u, '')
}

/**
 * 城市名 → 中国天气网城市码。
 *
 * 依次尝试：原名 → 去后缀 → 拼音。查不到返回 null（调用方会退回 open-meteo）。
 */
export function lookupCityCode(raw: string): string | null {
  if (!raw) return null

  const trimmed = raw.trim()
  const direct = CITY_CODES[trimmed]
  if (direct) return direct

  const stripped = normalize(trimmed)
  const byStripped = CITY_CODES[stripped]
  if (byStripped) return byStripped

  const ascii = stripped.toLowerCase().replace(/[-_]/g, '')
  const mapped = PINYIN_TO_NAME[ascii]
  if (mapped) return CITY_CODES[mapped] ?? null

  return null
}

