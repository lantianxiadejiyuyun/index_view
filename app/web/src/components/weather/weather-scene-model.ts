/** Match a city or administrative address, never a similarly named street. */
export function citySilhouette(city: string): CitySilhouette {
  const normalized = city.normalize('NFKC').trim().toLowerCase()
  return citySilhouettes.find((entry) => entry.aliases.some((alias) => {
    if (/^[\u3400-\u9fff]+$/u.test(alias)) {
      return new RegExp(String.raw`(?:^|中国|省|自治区|[\s,，/·-])${alias}(?:市|特别行政区|特別行政區|$|[\s,，/·-])`, 'u').test(normalized)
    }
    return normalized.split(/[,，/·]/u).some((part) => part.trim().replace(/\s+city$/u, '') === alias)
  })) ?? genericCitySilhouette
}
